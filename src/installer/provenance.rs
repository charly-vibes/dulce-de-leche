//! Release provenance and checksum policy enforcement (DDL-wof, SEC-03/06).

use super::*;
use crate::error::{DdlError, Result};

/// DDL-yts policy for release downloads, as a pure decision (no network, no
/// filesystem) so it can be regression-tested without connectivity.
///
/// - `ChecksumLookup::Published(digest)` → sha256 must match: `Ok(Verified)`
///   or `Err(ChecksumMismatch)`. A mismatch is NEVER bypassed by
///   `allow_unverified` and never falls back to cargo.
/// - `ChecksumLookup::Unavailable(reason)` → `Err(ChecksumUnavailable)` by
///   default (secure default: reject unverified downloads before any
///   destination mutation). Only when the user explicitly authorized the
///   legacy-unverified transition (`DDL_ALLOW_UNVERIFIED_RELEASE=1`) does it
///   return `Ok(UnverifiedAuthorized)`.
pub fn enforce_checksum_policy(
    tool: &str,
    url: &str,
    lookup: ChecksumLookup,
    bytes: &[u8],
    allow_unverified: bool,
) -> Result<VerificationStatus> {
    match lookup {
        ChecksumLookup::Published(expected) => {
            verify_checksum(bytes, &expected, tool, url)?;
            Ok(VerificationStatus::Verified)
        }
        ChecksumLookup::Unavailable(reason) => {
            if allow_unverified {
                Ok(VerificationStatus::UnverifiedAuthorized)
            } else {
                Err(DdlError::ChecksumUnavailable {
                    tool: tool.to_string(),
                    url: url.to_string(),
                    reason: reason.to_string(),
                })
            }
        }
    }
}

/// True only when the user explicitly authorized a legacy-unverified install.
pub(crate) fn unverified_authorized() -> bool {
    matches!(
        std::env::var("DDL_ALLOW_UNVERIFIED_RELEASE").as_deref(),
        Ok("1" | "true" | "yes")
    )
}

// -------------------------------------------------------------------------
// DDL-wof (SEC-03/06): publisher / build-identity verification.
// -------------------------------------------------------------------------

/// Trust root: the workflow name that is allowed to build release
/// artifacts fleet-wide (DDL-wof, §standardization — every repo's release
/// workflow is named `Release`). The expected *repository* is not a
/// constant: it is derived from the archive URL (DDL-9x4.1), because ddl
/// installs many fleet tools, each published by its own repository.
pub const EXPECTED_PROVENANCE_WORKFLOW: &str = "Release";

/// Derive the expected provenance repository (`owner/repo`) from a GitHub
/// release archive URL (`https://github.com/<owner>/<repo>/releases/download/…`).
/// Returns `None` for URLs that do not carry the structure — the policy
/// already rejects tagless URLs before identity is checked (DDL-9x4.1).
pub(crate) fn expected_repository_from_url(archive_url: &str) -> Option<String> {
    let rest = archive_url.split_once("releases/download/")?.0;
    let path = rest.trim_end_matches('/');
    let mut segs = path.split('/').rev();
    let repo = segs.next()?;
    let owner = segs.next()?;
    if owner.is_empty() || repo.is_empty() {
        return None;
    }
    Some(format!("{owner}/{repo}"))
}

/// The provenance manifest a release publishes next to its assets (DDL-wof).
/// Generated by the release workflow; binds each artifact's digest to the
/// repository/workflow/tag identity that produced the release.
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize)]
pub struct ProvenanceManifest {
    /// GitHub repository that built and published the release.
    pub repository: String,
    /// Name of the workflow that built the release.
    pub workflow: String,
    /// Tag the release was published under.
    pub tag: String,
    /// sha256 digest per artifact filename (lowercase hex).
    #[serde(default)]
    pub artifacts: std::collections::HashMap<String, String>,
}

/// Result of looking up the release's provenance manifest (DDL-wof).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProvenanceLookup {
    /// The release publishes a well-formed provenance manifest.
    Published(ProvenanceManifest),
    /// No usable provenance manifest: missing, malformed, unreadable, or the
    /// fetch failed. The string is the human-readable reason used in
    /// rejection diagnostics.
    Unavailable(&'static str),
}

/// DDL-wof policy for release build identity, as a pure decision (no network,
/// no filesystem) so it can be regression-tested without connectivity.
///
/// - Identity checks are NEVER bypassed: a published manifest naming an
///   unexpected repository, workflow, or tag — or listing a digest that does
///   not match the downloaded bytes — is rejected even when the user
///   authorized unverified installs. Authorization only bridges a *missing*
///   manifest (like DDL-yts) or an archive URL with no tag to check against.
/// - A manifest that fails identity or digest binding yields
///   `ChecksumMismatch` for digest divergence (bytes altered) and
///   `ChecksumUnavailable` for identity/availability violations — reusing the
///   SEC-03 rejection plumbing so no destination mutation can happen.
///
/// Build the standard rejection error for the provenance policy.
fn provenance_reject(tool: &str, url: &str, reason: String) -> DdlError {
    DdlError::ChecksumUnavailable {
        tool: tool.to_string(),
        url: url.to_string(),
        reason,
    }
}

/// Resolve the release tag authorization: without a tag the provenance
/// identity (repository/workflow/tag) cannot be checked, so the download is
/// only allowed under the explicit legacy-unverified transition.
fn authorize_tag(
    expected_tag: Option<&str>,
    allow_unverified: bool,
    tool: &str,
    url: &str,
) -> Result<Option<String>> {
    let Some(tag) = expected_tag else {
        if allow_unverified {
            return Ok(None);
        }
        return Err(provenance_reject(tool, url, "archive URL does not carry a release tag, so the provenance identity (repository/workflow/tag) cannot be checked".to_string()));
    };
    Ok(Some(tag.to_string()))
}

/// Resolve the provenance manifest: a missing manifest is only authorized
/// under the explicit legacy-unverified transition; a contradicting one
/// never is (DDL-yts: verification must be available, not merely attempted).
fn resolve_manifest(
    lookup: ProvenanceLookup,
    allow_unverified: bool,
    tool: &str,
    url: &str,
) -> Result<Option<ProvenanceManifest>> {
    match lookup {
        ProvenanceLookup::Unavailable(reason) => {
            if allow_unverified {
                return Ok(None);
            }
            Err(provenance_reject(
                tool,
                url,
                format!("no usable provenance manifest: {reason}"),
            ))
        }
        ProvenanceLookup::Published(manifest) => Ok(Some(manifest)),
    }
}

/// Bind the manifest identity (repository/workflow/tag) to the fetch URL.
fn verify_provenance_identity(
    manifest: &ProvenanceManifest,
    url: &str,
    tag: &str,
    tool: &str,
) -> Result<()> {
    let reject = |reason: String| provenance_reject(tool, url, reason);
    let expected_repository = expected_repository_from_url(url).ok_or_else(|| {
        reject(
            "archive URL does not carry a github.com/<owner>/<repo>/releases/download path, so the provenance repository cannot be derived"
                .to_string(),
        )
    })?;
    if manifest.repository != expected_repository {
        return Err(reject(format!(
            "provenance manifest declares repository `{}`, expected `{}`",
            manifest.repository, expected_repository
        )));
    }
    if manifest.workflow != EXPECTED_PROVENANCE_WORKFLOW {
        return Err(reject(format!(
            "provenance manifest declares workflow `{}`, expected `{}`",
            manifest.workflow, EXPECTED_PROVENANCE_WORKFLOW
        )));
    }
    if manifest.tag != tag {
        return Err(reject(format!(
            "provenance manifest describes tag `{}`, but the asset was fetched from release `{tag}`",
            manifest.tag
        )));
    }
    Ok(())
}

/// Bind the manifest's per-asset digest to the downloaded bytes.
fn verify_asset_digest(
    manifest: &ProvenanceManifest,
    url: &str,
    bytes: &[u8],
    tool: &str,
) -> Result<VerificationStatus> {
    let asset = url.rsplit_once('/').map(|(_, a)| a).unwrap_or(url);
    match manifest.artifacts.get(asset) {
        None => Err(provenance_reject(
            tool,
            url,
            format!("provenance manifest does not list asset `{asset}`"),
        )),
        Some(expected) => {
            verify_checksum(bytes, expected, tool, url)?;
            Ok(VerificationStatus::Verified)
        }
    }
}

pub fn enforce_provenance_policy(
    tool: &str,
    url: &str,
    expected_tag: Option<&str>,
    lookup: ProvenanceLookup,
    bytes: &[u8],
    allow_unverified: bool,
) -> Result<VerificationStatus> {
    let Some(tag) = authorize_tag(expected_tag, allow_unverified, tool, url)? else {
        return Ok(VerificationStatus::UnverifiedAuthorized);
    };
    let Some(manifest) = resolve_manifest(lookup, allow_unverified, tool, url)? else {
        return Ok(VerificationStatus::UnverifiedAuthorized);
    };
    verify_provenance_identity(&manifest, url, &tag, tool)?;
    verify_asset_digest(&manifest, url, bytes, tool)
}

/// DDL-9x4.11.1: origin-scoped verification of release archive bytes, as a
/// pure decision (no network, no filesystem) so it can be regression-tested
/// without connectivity. Combines the DDL-yts checksum policy and the DDL-wof
/// provenance policy with one distinction neither enforces alone:
///
/// - charly-vibes origins (`github.com/charly-vibes/…`) keep the strict
///   channel: checksum + provenance identity must BOTH accept. They NEVER
///   fall back to checksums-only, no matter what the checksums.txt says.
/// - external origins (e.g. bd from gastownhall/beads) can never publish our
///   provenance.json, so they verify through the release's own
///   checksums.txt / per-asset digest instead — accepted as
///   [`VerificationStatus::ChecksumsVerified`], a deliberately distinct
///   weaker status. No usable checksum still rejects fail-closed, and a
///   published mismatch is never bypassed (same rules as DDL-yts).
/// - Explicit `DDL_ALLOW_UNVERIFIED_RELEASE` authorization keeps its
///   meaning for both channels: it only bridges a MISSING checksum, never a
///   published mismatch or a charly-vibes identity violation.
pub fn verify_release_bytes(
    tool: &str,
    url: &str,
    checksum: ChecksumLookup,
    provenance: ProvenanceLookup,
    bytes: &[u8],
    allow_unverified: bool,
) -> Result<VerificationStatus> {
    let charly_vibes_origin = charly_vibes_origin(url);
    let status = enforce_checksum_policy(tool, url, checksum, bytes, allow_unverified)?;
    if !charly_vibes_origin {
        return Ok(match status {
            // Weaker channel: checksum-authenticated only, no identity proof.
            VerificationStatus::Verified => VerificationStatus::ChecksumsVerified,
            other => other,
        });
    }
    enforce_provenance_policy(
        tool,
        url,
        release_tag_from_url(url),
        provenance,
        bytes,
        allow_unverified,
    )?;
    Ok(status)
}

/// The GitHub organization whose releases must carry our provenance
/// manifest (DDL-9x4.11.1): every other origin uses the checksums-only
/// channel.
const CHARLY_VIBES_ORG: &str = "charly-vibes";

/// True when the archive URL points at a charly-vibes release — the only
/// origin required to publish our provenance.json.
pub(crate) fn charly_vibes_origin(archive_url: &str) -> bool {
    expected_repository_from_url(archive_url)
        .and_then(|repo| {
            repo.split_once('/')
                .map(|(owner, _)| owner == CHARLY_VIBES_ORG)
        })
        .unwrap_or(false)
}

/// Extract the release tag from a GitHub release download URL
/// (`…/releases/download/<tag>/<asset>`). `None` when the URL does not carry
/// one — provenance identity cannot be checked against a non-release URL.
pub(crate) fn release_tag_from_url(archive_url: &str) -> Option<&str> {
    let rest = archive_url.split_once("releases/download/")?.1;
    rest.split('/').next().filter(|t| !t.is_empty())
}

/// Fetch the release's provenance manifest (`provenance.json` next to the
/// asset, DDL-wof). Any flavor of "verification is not possible" — missing
/// asset, malformed JSON, unreadable body, transport failure — is reported as
/// [`ProvenanceLookup::Unavailable`] with the precise reason; the policy in
/// `enforce_provenance_policy` decides rejection, not this lookup.
pub(crate) fn fetch_provenance(archive_url: &str, _verbose: bool) -> ProvenanceLookup {
    let Some((base, _)) = archive_url.rsplit_once('/') else {
        return ProvenanceLookup::Unavailable("asset URL has no parent path");
    };
    let provenance_url = format!("{base}/provenance.json");
    match reqwest::blocking::get(&provenance_url) {
        Ok(resp) if resp.status().is_success() => match resp.bytes() {
            Ok(body) => match serde_json::from_slice::<ProvenanceManifest>(&body) {
                Ok(manifest) => ProvenanceLookup::Published(manifest),
                Err(_) => ProvenanceLookup::Unavailable("provenance.json is malformed"),
            },
            Err(_) => ProvenanceLookup::Unavailable("provenance.json body could not be read"),
        },
        // A non-success (404, 403, …) is indistinguishable from "no manifest
        // published" and must not degrade to skip-and-install — the policy
        // rejects unless explicitly authorized.
        Ok(_) => ProvenanceLookup::Unavailable("release publishes no provenance.json asset"),
        Err(_) => ProvenanceLookup::Unavailable("provenance.json could not be fetched"),
    }
}
